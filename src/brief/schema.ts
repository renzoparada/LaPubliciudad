/** Opción con valor explícito (los valores los usa el motor de diagnóstico). */
const o = (value: string, label: string): Option => ({ value, label });

/** Lista simple: el valor es el slug de la etiqueta. */
export const slug = (s: string) =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "");
const list = (...labels: string[]): Option[] => labels.map((l) => o(slug(l), l));

